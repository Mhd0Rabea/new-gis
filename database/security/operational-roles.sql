-- MGOS operational roles. Set passwords outside this repository:
-- ALTER ROLE mgos_editor PASSWORD '<secret-from-password-manager>';
-- ALTER ROLE mgos_geoserver PASSWORD '<secret-from-password-manager>';
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='mgos_editor') THEN
  CREATE ROLE mgos_editor LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
 END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='mgos_geoserver') THEN
  CREATE ROLE mgos_geoserver LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
 END IF;
END $$;

REVOKE CREATE ON SCHEMA mgos FROM PUBLIC, mgos_editor, mgos_geoserver;
GRANT USAGE ON SCHEMA mgos TO mgos_editor, mgos_geoserver;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA mgos TO mgos_editor;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA mgos TO mgos_editor;
GRANT SELECT ON ALL TABLES IN SCHEMA mgos TO mgos_geoserver;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER ON ALL TABLES IN SCHEMA mgos FROM mgos_geoserver;

ALTER DEFAULT PRIVILEGES IN SCHEMA mgos GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO mgos_editor;
ALTER DEFAULT PRIVILEGES IN SCHEMA mgos GRANT USAGE, SELECT ON SEQUENCES TO mgos_editor;
ALTER DEFAULT PRIVILEGES IN SCHEMA mgos GRANT SELECT ON TABLES TO mgos_geoserver;
